# --- Human-readable feature name translator ---
def make_feature_readable(feature_name, value):
    """Convert one-hot encoded / raw model features into human-readable descriptions."""
    one_hot_prefixes = [
        "Contract_", "InternetService_", "PaymentMethod_", "MultipleLines_",
        "OnlineSecurity_", "OnlineBackup_", "DeviceProtection_", "TechSupport_",
        "StreamingTV_", "StreamingMovies_"
    ]
    for prefix in one_hot_prefixes:
        if feature_name.startswith(prefix):
            category = feature_name[len(prefix):]
            clean_prefix = prefix.replace("_", "")
            return f"{clean_prefix}: {category}" if value == 1 else f"{clean_prefix}: not {category}"

    binary_names = {
        "gender": "Gender", "SeniorCitizen": "Senior citizen", "Partner": "Partner",
        "Dependents": "Dependents", "PhoneService": "Phone service", "PaperlessBilling": "Paperless billing"
    }
    if feature_name in binary_names:
        readable_name = binary_names[feature_name]
        readable_value = ("Male" if value == 1 else "Female") if feature_name == "gender" \
            else ("Yes" if value == 1 else "No")
        return f"{readable_name}: {readable_value}"

    numeric_names = {"tenure": "Customer tenure (months)", "MonthlyCharges": "Monthly charges",
                      "TotalCharges": "Total charges"}
    if feature_name in numeric_names:
        return f"{numeric_names[feature_name]}: {value}"

    return f"{feature_name}: {value}"

