def predict_churn(customer_data, threshold=0.5):
    """Predict churn for one customer (dict) or many (list of dicts)."""
    model = joblib.load("churn_final_model.pkl")
    features = joblib.load("churn_model_features.pkl")
    single = isinstance(customer_data, dict)
    records = [customer_data] if single else customer_data
    df_in = pd.DataFrame(records)
    for col in features:
        if col not in df_in.columns:
            df_in[col] = 0
    df_in = df_in[features]
    probas = model.predict_proba(df_in)[:, 1]
    predictions = (probas >= threshold).astype(int)
    segments = ["High" if p >= 0.65 else "Medium" if p >= 0.35 else "Low" for p in probas]
    if single:
        return {"churn_probability": round(float(probas[0]), 4),
                "churn_prediction": int(predictions[0]),
                "risk_segment": segments[0]}
    return {"churn_probability": [round(float(p), 4) for p in probas],
            "churn_prediction": predictions.tolist(),
            "risk_segment": segments}

